// mask.ts — 외부 AI로 보내기 전 고객 문장의 개인정보 제거 (순수 함수, 서버 전용)
// 원칙: 의미(주제어)는 남기고 식별 가능한 정보만 자리표시자로 바꾼다. 확신이 없으면 더 많이 지운다.

const RULES: [RegExp, string][] = [
  // URL(이메일보다 먼저: 주소 안의 @ 등)
  [/https?:\/\/[^\s)]+/gi, '[주소링크]'],
  [/[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g, '[이메일]'],
  // 전화: 010-1234-5678 / 010 1234 5678 / 01012345678 / +82 10-… / 지역번호
  [/(?:\+?82[\s-]?)?0?1[0-9][\s.-]?\d{3,4}[\s.-]?\d{4}/g, '[전화]'],
  [/\b0\d{1,2}[\s.-]\d{3,4}[\s.-]\d{4}\b/g, '[전화]'],
  // 예약코드: CS2609001, CZ-123456 등 영문 2자 + 숫자 6자 이상
  [/\b[A-Za-z]{2}-?\d{6,}\b/g, '[예약코드]'],
  // 성함: "성함은 홍길동", "이름: 김철수", "저는 김철수 고객"
  [/(성함|이름|성명)\s*(?:은|는|이|가|:)?\s*[가-힣]{2,4}/g, '$1 [이름]'],
  [/저는\s*[가-힣]{2,4}(?=\s*(?:고객|입니다|이에요|예요|이고|인데))/g, '저는 [이름]'],
  [/[가-힣]{2,4}\s*(?=고객님|님\s*(?:입니다|이에요))/g, '[이름] '],
  // 주소: 시/도 + 구/군/시 + 도로명/지번, 또는 도로명 + 번지
  [/(?:[가-힣]+(?:특별시|광역시|특별자치시|특별자치도|도|시))\s*[가-힣]+(?:구|군|시)\s*[가-힣0-9]+(?:로|길|동|읍|면)\s*\d{0,4}(?:번길)?\s*\d{0,4}(?:-\d+)?/g, '[주소]'],
  [/[가-힣0-9]+(?:로|길)\s*\d{1,4}(?:번길)?\s*\d{0,4}(?:-\d+)?/g, '[주소]'],
  // 긴 숫자열(계좌·주민번호·카드번호 등)
  [/\d[\d\s-]{5,}\d/g, '[숫자]'],
]

export function maskPersonalInfo(text: string): string {
  let out = text ?? ''
  for (const [re, rep] of RULES) out = out.replace(re, rep)
  return out.replace(/\s{2,}/g, ' ').trim()
}

/** 마스킹 후에도 연락처·이메일·긴 숫자가 남아 있으면 외부로 보내면 안 된다 */
export function isSafeToSend(maskedText: string): boolean {
  return !/\d{6,}/.test(maskedText.replace(/\s/g, '')) && !/@/.test(maskedText) && !/https?:\/\//i.test(maskedText)
}
