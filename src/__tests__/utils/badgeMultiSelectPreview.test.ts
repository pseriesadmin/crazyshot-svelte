import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import path from 'node:path'

/**
 * 배지목록 패널 — 배지 여러 개(개수 제한 없음) 선택 + 미선택 배경 없음 + 고객 썸네일 적용 미리보기 (2026-11-16, Stephen 지시, Migration #830)
 */
const read = (p: string) => readFileSync(path.resolve(process.cwd(), p), 'utf8')
const panel = read('src/lib/components/cms/badge/BadgeRulePanel.svelte')
const server = read('src/routes/cms/promotion/ad/+page.server.ts')
const card = read('src/lib/components/products/ProductDPCard.svelte')
const sql = read('supabase/migrations/20261116120000_830_badge_multi_templates.sql')

describe('배지목록 패널 — 다중 선택', () => {
  it('배지를 토글로 여러 개 고르고(선택 순서 유지) 개수 상한을 두지 않는다', () => {
    expect(panel).toContain('let templateIds = $state<string[]>')
    expect(panel).toContain('function toggleTemplate')
    expect(panel).toContain('aria-pressed={templateIds.includes(t.id)}')
    expect(panel).not.toMatch(/templateIds\.length\s*>=\s*\d/)
  })
  it('저장 시 template_ids 를 보내고 1개 이상일 때만 저장된다', () => {
    expect(panel).toContain('template_ids: templateIds')
    expect(panel).toContain("templateIds.length === 0")
    expect(server).toContain("f.getAll('template_ids')")
    expect(server).toContain('p_template_ids: templateIds')
  })
  it('DB: template_ids 배열 + 비어 있으면 template_id 폴백 + 사용 중 판정에 포함', () => {
    expect(sql).toContain('ADD COLUMN IF NOT EXISTS template_ids uuid[]')
    expect(sql).toContain("COALESCE(NULLIF(b.template_ids, '{}'::uuid[]), ARRAY[b.template_id])")
    expect(sql).toContain('p_id = ANY(template_ids)')
    expect(sql).not.toMatch(/LIMIT\s+\d|\[1:3\]|cardinality\(v_tpls\)\s*>\s*\d/)
  })
})

describe('배지 목록(왼쪽 카드) — 품번', () => {
  const tab = read('src/lib/components/cms/badge/BadgeTab.svelte')
  const loader = read('src/routes/cms/promotion/ad/+page.server.ts')
  const sql831 = read('supabase/migrations/20261116130000_831_badge_list_no.sql')
  it('카드에 만들 때 부여된 고유 품번(No.001 형식)을 보여 준다 — 목록 순서(i)로 만들지 않는다', () => {
    expect(tab).toContain('{formatBadgeNo(r.badge_no)}')
    expect(tab).not.toContain('{i + 1}')
    expect(tab).toContain('{#snippet renderItem(r: BadgeRule)}')
  })
  it('DB: INSERT 때 자동 부여(IDENTITY)·고유·기존 행은 만든 순서로 채번, 저장 함수는 바꾸지 않는다', () => {
    expect(sql831).toContain('GENERATED BY DEFAULT AS IDENTITY')
    expect(sql831).toContain('CREATE UNIQUE INDEX IF NOT EXISTS product_badges_badge_no_key')
    expect(sql831).toContain('ORDER BY created_at, id')
    expect(sql831).not.toMatch(/CREATE OR REPLACE FUNCTION|DROP FUNCTION/)
  })
  it('조회는 열이 없는 환경에서도 이전 열만으로 폴백한다(배포 순서 사고 방지)', () => {
    expect(loader).toContain('template_ids, badge_no')
  })
  it('패널 제목 오른쪽에 배정된 품번을 단순 텍스트로 보여 준다 — 새 배지목록은 아직 품번이 없어 숨긴다', () => {
    const head = panel.slice(panel.indexOf('<div class="title-group">'), panel.indexOf('<div class="head-actions">'))
    expect(head).toContain('section-title')
    expect(head).toContain('{#if rule?.badge_no !== undefined}')
    expect(head).toContain('{formatBadgeNo(rule.badge_no)}')
    expect(head.indexOf('section-title')).toBeLessThan(head.indexOf('panel-no'))
    const css = panel.slice(panel.indexOf('.panel-no {'))
    const rule = css.slice(0, css.indexOf('}'))
    expect(rule).not.toContain('background')
    expect(panel).toContain('.title-group { display: flex; align-items: baseline; gap: 12px;')
  })
  it('배지 선택 칸(패널)에는 번호를 붙이지 않는다', () => {
    expect(panel).not.toContain('tpl-no')
  })
})

describe('배지목록 패널 — 미선택 배경 제거', () => {
  it('.tpl 기본 배경은 transparent, 선택만 퍼플, 호버는 배경색 변경만', () => {
    const css = panel.slice(panel.indexOf('.tpl {'))
    const base = css.slice(0, css.indexOf('}'))
    expect(base).toContain('background: transparent')
    expect(base).not.toContain('--cs-lilac')
    expect(panel).toContain('.tpl.active { background: var(--cs-purple); }')
    expect(panel).toContain('.tpl:hover:not(.active) { background: var(--cs-surface-gray); }')
  })
})

describe('배지목록 패널 — 배지가 많아지면 스크롤', () => {
  it('선택 목록은 미리보기 높이(--pc-thumb-size)를 넘지 않고 세로 스크롤한다', () => {
    const css = panel.slice(panel.indexOf('.tpl-grid {'))
    const rule = css.slice(0, css.indexOf('}'))
    expect(rule).toContain('max-height: var(--pc-thumb-size)')
    expect(rule).toContain('overflow-y: auto')
    expect(panel).toContain('--pc-thumb-size: 174px')
  })
})

describe('배지목록 패널 — 고객 썸네일 적용 미리보기', () => {
  it('배지 선택 목록 오른쪽에 고객 카드와 같은 컴포넌트(ProductDPCard thumb)로 적용 상태를 그린다', () => {
    expect(panel).toContain("<ProductDPCard variant=\"thumb\"")
    expect(panel).toContain('badges={previewBadges}')
    expect(panel.indexOf('class="tpl-grid"')).toBeLessThan(panel.indexOf('class="badge-preview"'))
  })
  it('사진 자리는 실제 상품 이미지 중 하나를 무작위로 깔고(패널 마운트 시 1회), 후보가 없으면 빈 이미지로 대체한다', () => {
    expect(panel).toContain('sampleImages[Math.floor(Math.random() * sampleImages.length)]')
    expect(panel).toContain('imageUrl={PREVIEW_IMG}')
    expect(server).toContain("image_urls")
    expect(server).toContain('sampleImages')
    // 이미지 없는 상품이 대부분인 환경에서도 후보가 비지 않도록 이미지 있는 상품만 읽는다
    expect(server).toMatch(/\.neq\('image_urls', '\[\]'\)[^\n]*\n\s*\.limit\(200\)/)
  })
  it('선택한 순서대로 이미지형·바형을 모두 넘긴다(상한 없음)', () => {
    expect(panel).toContain('templateIds')
    const fn = panel.slice(panel.indexOf('const previewBadges'), panel.indexOf('// ── 상품 검색'))
    expect(fn).not.toContain('.slice(')
  })
})

describe('고객 카드 — 개수 상한 제거', () => {
  it('ProductDPCard 가 배지를 자르지 않고 badge_id:template_id 키로 그린다', () => {
    expect(card).not.toContain('MAX_VISIBLE_BADGES')
    expect(card).not.toContain('badges.slice(')
    expect(card).toContain('`${b.badge_id}:${b.template_id}`')
    expect(card).toContain('badgeSize ?? 22')
    expect(card).toContain('badgeSize ?? 16')
  })
})
