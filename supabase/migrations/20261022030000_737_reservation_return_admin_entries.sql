CREATE TABLE IF NOT EXISTS public.reservation_return_admin_entries (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id bigint NOT NULL REFERENCES public.rental_reservations(id) ON DELETE CASCADE,
  registered_by  uuid,
  memo           text,
  checklist      text[] NOT NULL DEFAULT '{}',
  media          jsonb  NOT NULL DEFAULT '[]'::jsonb,
  created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS reservation_return_admin_entries_rsv_idx
  ON public.reservation_return_admin_entries (reservation_id, created_at DESC);

ALTER TABLE public.reservation_return_admin_entries ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.reservation_return_admin_entries FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.reservation_return_admin_entries TO service_role;
