-- #831 배지 목록 품번 — 배지목록(product_badges)을 만들 때 한 번 부여되는 고유번호(영구 고정, 재사용 없음, 순서·삭제와 무관)
-- 적용 순서: Stage(ezyvffjvuwmtuhpxdjrw) → Production(vnbpmvxruyciuuaermyh). 코드는 이 열이 없어도 동작하므로(조회 폴백) 배포 순서 제약은 없다.
-- 롤백: DROP INDEX public.product_badges_badge_no_key; ALTER TABLE public.product_badges ALTER COLUMN badge_no DROP IDENTITY; ALTER TABLE public.product_badges DROP COLUMN badge_no;
--
-- 규칙: 품번은 INSERT 때 자동 부여된다(IDENTITY) — 저장 함수(cms_save_product_badge)는 바꾸지 않는다. 삭제(soft delete)된 행의 번호도 그대로 남아 다시 쓰이지 않는다.
--       기존 행은 만든 순서(created_at)대로 1부터 번호를 받는다.

ALTER TABLE public.product_badges ADD COLUMN IF NOT EXISTS badge_no integer;

WITH n AS (
  SELECT id, row_number() OVER (ORDER BY created_at, id) AS rn FROM public.product_badges
)
UPDATE public.product_badges b SET badge_no = n.rn FROM n WHERE n.id = b.id AND b.badge_no IS NULL;

DO $$
DECLARE
  v_max integer;
BEGIN
  SELECT COALESCE(max(badge_no), 0) INTO v_max FROM public.product_badges;
  ALTER TABLE public.product_badges ALTER COLUMN badge_no SET NOT NULL;
  IF NOT EXISTS (
    SELECT 1 FROM pg_attribute
     WHERE attrelid = 'public.product_badges'::regclass AND attname = 'badge_no' AND attidentity <> ''
  ) THEN
    EXECUTE format('ALTER TABLE public.product_badges ALTER COLUMN badge_no ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)', v_max + 1);
  END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS product_badges_badge_no_key ON public.product_badges (badge_no);
