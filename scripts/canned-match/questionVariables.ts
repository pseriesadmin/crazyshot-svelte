/** 모든 어근(중복 제거) — 키워드 커버리지 점검용 */
export function allRoots(): string[] {
  const out = new Set<string>()
  for (const group of Object.values(ALL_SLOTS)) for (const slot of Object.values(group)) for (const r of slot.roots) out.add(r)
  return [...out]
}

/** 슬롯 개수·어근 수·말투 변형 수 요약 */
export function summarize(): { groups: number; slots: number; roots: number; phrases: number } {
  let slots = 0
  let phrases = 0
  for (const group of Object.values(ALL_SLOTS)) for (const slot of Object.values(group)) { slots++; phrases += slot.phrases.length }
  return { groups: Object.keys(ALL_SLOTS).length, slots, roots: allRoots().length, phrases }
}
